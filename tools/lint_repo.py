"""Keep game-derived files out of this repository.

The repository holds tools only. Shader bytecode, SGO / CPK containers, disassembly, decompiled HLSL and the
manifests the tool writes all come from the game and stay on each user's own machine.

  python -B tools/lint_repo.py                       check every tracked file (and untracked, not ignored ones)
  python -B tools/lint_repo.py --history BASE...HEAD every file version each commit in the range added or modified

Exit code 0 clean, 1 problems found.
"""
from __future__ import annotations

import argparse
from pathlib import PurePosixPath
import subprocess
import sys

MAX_SIZE = 512 * 1024

# Game containers, shader programs and shader sources. Original shaders are not accepted either: the repository is
# tools only, and a decompiled game shader is hard to tell from one written from scratch.
BLOCKED_SUFFIXES = {
    '.sgo', '.dsgo', '.cpk', '.dxbc', '.cso', '.shdr', '.fxo', '.dxil', '.spv',
    '.hlsl', '.hlsli', '.fx', '.fxh', '.asm', '.ps', '.vs',
    '.mdb', '.rab', '.rmpa', '.mtx', '.bvm', '.dds', '.exe', '.dll', '.pdb', '.zip', '.7z', '.rar',
}
# Outputs of shader_sgo.py extract.
BLOCKED_NAMES = {'manifest.json', 'provenance.json'}

# File magics at offset 0. 'SGO\0' little-endian and '\0OGS' big-endian.
BLOCKED_MAGICS = (b'DXBC', b'SGO\x00', b'\x00OGS', b'DSGO', b'CPK ', b'MZ', b'PK\x03\x04', b'DDS ')

# Text a disassembler or decompiler writes. Split so this file does not match itself.
BLOCKED_TEXT = (
    'Generated by Microsoft (R) ' + 'HLSL Shader Compiler',
    '// ---- Created with ' + '3Dmigoto',
    'dcl_' + 'globalFlags',
    'dcl_' + 'constantbuffer',
)


def check(path: str, data: bytes) -> list[str]:
    """Problems with one file version (empty: fine)."""
    name = PurePosixPath(path)
    problems = []
    if name.suffix.lower() in BLOCKED_SUFFIXES:
        problems.append(f'{path}: {name.suffix} files are game data or shader code; keep them out of the repository')
    if name.name.lower() in BLOCKED_NAMES:
        problems.append(f'{path}: looks like shader_sgo.py extract output')
    for magic in BLOCKED_MAGICS:
        if data.startswith(magic):
            problems.append(f'{path}: starts with {magic!r}, a binary game or archive format')
            break
    if len(data) > MAX_SIZE:
        problems.append(f'{path}: {len(data)} bytes, over the {MAX_SIZE}-byte limit for a tools repository')
    if b'\0' in data[:8192] and not problems:
        problems.append(f'{path}: binary file; only source code and documentation belong here')
    text = data.decode('utf-8', 'replace')
    for marker in BLOCKED_TEXT:
        if marker in text:
            problems.append(f'{path}: contains {marker!r}, the output of a shader disassembler or decompiler')
            break
    return problems


def _git(*args: str) -> bytes:
    return subprocess.run(['git', *args], check=True, capture_output=True).stdout


def working_tree() -> list[str]:
    names = _git('ls-files', '-z', '--cached', '--others', '--exclude-standard').split(b'\0')
    problems = []
    for raw in filter(None, names):
        path = raw.decode('utf-8', 'surrogateescape')
        try:
            with open(path, 'rb') as file:
                data = file.read()
        except FileNotFoundError:   # deleted but not staged
            continue
        problems += check(path, data)
    return problems


def history(spec: str) -> list[str]:
    problems = []
    for commit in _git('rev-list', '--reverse', spec.replace('...', '..')).decode().split():
        changed = _git('diff-tree', '-z', '-r', '--no-commit-id', '--root', '--name-only', '--diff-filter=AMRC',
                       commit).split(b'\0')
        for raw in filter(None, changed):
            path = raw.decode('utf-8', 'surrogateescape')
            data = _git('show', f'{commit}:{path}')
            problems += [f'{commit[:10]} {p}' for p in check(path, data)]
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--history', metavar='BASE...HEAD', help='check every commit in this range instead')
    args = parser.parse_args(argv)
    problems = history(args.history) if args.history else working_tree()
    for problem in problems:
        print(problem)
    print(f'{len(problems)} problem(s)')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
