"""The guard that keeps game-derived files out of the repository."""
from __future__ import annotations

from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import lint_repo  # noqa: E402


class CheckTests(unittest.TestCase):
    def test_source_and_docs_pass(self) -> None:
        self.assertEqual(lint_repo.check('shader_sgo.py', b'print("hi")\n'), [])
        self.assertEqual(lint_repo.check('README.md', '# Shader tools\n'.encode()), [])

    def test_blocks_game_formats_by_name(self) -> None:
        for path in ('SND_MECH.SGO', 'out/0001.ps_5_0.dxbc', 'x/0001.ps_5_0.hlsl', 'x/0001.ps_5_0.asm',
                     'DX11.cpk', 'extract/manifest.json', 'extract/provenance.json'):
            with self.subTest(path=path):
                self.assertTrue(lint_repo.check(path, b'x'))

    def test_blocks_game_formats_by_content(self) -> None:
        for data in (b'DXBC' + bytes(28), b'SGO\x00\x02\x01', b'\x00OGS', b'CPK     '):
            with self.subTest(data=data):
                self.assertTrue(lint_repo.check('renamed.txt', data))

    def test_blocks_disassembly_and_decompiler_output_in_any_file(self) -> None:
        for text in ('ps_5_0\n' + 'dcl_' + 'globalFlags refactoringAllowed\n',
                     '// ---- Created with ' + '3Dmigoto v1.3.16\n',
                     '// Generated by Microsoft (R) ' + 'HLSL Shader Compiler 10.1\n'):
            with self.subTest(text=text[:20]):
                self.assertTrue(lint_repo.check('notes.md', text.encode()))

    def test_blocks_large_and_binary_files(self) -> None:
        self.assertTrue(lint_repo.check('big.txt', b'a' * (lint_repo.MAX_SIZE + 1)))
        self.assertTrue(lint_repo.check('blob.txt', b'abc\0def'))

    def test_repository_itself_is_clean(self) -> None:
        result = subprocess.run([sys.executable, '-B', str(ROOT / 'tools' / 'lint_repo.py')], cwd=ROOT,
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout)


class HistoryTests(unittest.TestCase):
    def test_file_added_and_removed_inside_the_range_is_still_caught(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            def git(*args: str) -> str:
                return subprocess.run(['git', '-c', 'user.name=t', '-c', 'user.email=t@example.invalid', *args],
                                      cwd=directory, check=True, capture_output=True, text=True).stdout.strip()
            git('init', '-q')
            (Path(directory) / 'a.py').write_text('x = 1\n')
            git('add', '.')
            git('commit', '-qm', 'base')
            base = git('rev-parse', 'HEAD')
            (Path(directory) / 'leak.dxbc').write_bytes(b'DXBC' + bytes(28))
            git('add', '.')
            git('commit', '-qm', 'add')
            git('rm', '-q', 'leak.dxbc')
            git('commit', '-qm', 'remove')
            head = git('rev-parse', 'HEAD')
            old = Path.cwd()
            try:
                import os
                os.chdir(directory)
                problems = lint_repo.history(f'{base}...{head}')
            finally:
                os.chdir(old)
            self.assertTrue(any('leak.dxbc' in p for p in problems), problems)


if __name__ == '__main__':
    unittest.main()
